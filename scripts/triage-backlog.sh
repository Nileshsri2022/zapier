#!/usr/bin/env bash
#
# Backlog triage pass — closes issues that are already fixed on `main`, or fixed
# by an open PR, and records the evidence on each one.
#
# Why this exists: several issues in this repo describe problems that were
# fixed without the issue being updated, so the backlog overstates the work
# left. `#56` is the worked example — 4 of its 5 items were already on `main`,
# and only the verify-token fallback was outstanding.
#
# Usage:
#   ./scripts/triage-backlog.sh            # dry run (default) — prints the plan
#   ./scripts/triage-backlog.sh --apply    # comment + close for real
#
# Requires `gh` authenticated with issues:write. A GitHub App installation
# token without that permission fails with "Resource not accessible by
# integration"; the script detects this on the first write and stops.
#
# The 2026-10-21 pass was applied through commit references instead (the
# sandbox token had no issues:write), so the nine issues below are already
# closed. What remains here is the reproducible verification: each verdict
# names the test that proves it. See docs/backlog-triage.md for the record.
#
set -uo pipefail

APPLY=0
[[ "${1:-}" == "--apply" ]] && APPLY=1

DISCLAIMER='> *This was generated by AI during triage.*'
REPO="$(gh repo view --json nameWithOwner --jq .nameWithOwner)"

# issue<TAB>verdict<TAB>evidence
PLAN=$(cat <<'EOF'
51	already-fixed	The egress guard landed: apps/worker/src/sendWebhook.ts:66 blocks loopback, link-local (incl. 169.254.169.254) and RFC1918 hosts before the request is made. Passing test: apps/worker/tests/sendWebhook.test.ts > "blocks loopback, private and metadata targets unless explicitly allowed".
55	already-fixed	Every ingress spec verifies over raw bytes (packages/ingress/src/specs.ts -> payload: 'raw'), so a re-serialized body is never signed. Passing test: packages/ingress/tests/ingress.test.ts > "rejects a signature computed over different bytes (no re-serialization)". GitHub is wired through verifyGithub at apps/server/src/routes/GitHubRoutes.ts:221.
45	already-fixed	apps/server/src/routes/GitHubRoutes.ts:203 reads x-github-delivery and dedupes on it. Passing test: apps/server/tests/triggers/github-contract.test.ts > "same delivery id redelivered → duplicate skipped, zero extra runs".
36	already-fixed	WhatsApp and Telegram outbound calls share one abort-signalled fetch transport. Passing test: apps/worker/tests/outboundTimeouts.test.ts > "sends through a bounded (abort-signalled) transport".
28	already-fixed	apps/hooks/src/telegramHandler.ts:242 scopes the trigger lookup to bot: { id: botId }, so an update can only fire the bot that received it. Passing test: apps/hooks/tests/telegramHandler.test.ts > "only loads triggers for the bot that received the update".
49	fixed-in-64	Fixed by PR #64 ("fix(server): validate filter operators at write time"). Merged as a32de17.
50	fixed-in-64	Fixed by PR #64 ("fix(worker): fail closed when a filter operator cannot be evaluated"). Merged as a32de17.
54	fixed-in-64	Fixed by PR #64 ("fix(hooks): drop the @botname mention from Telegram commandArgs"). Merged as a32de17.
56	fixed-in-64	Fixed by PR #64 ("fix(hooks): refuse WhatsApp verification when no token is configured"). Items 1, 2, 4 and 5 were already on main; item 3 was the outstanding one. Merged as a32de17.
58	fixed-in-64	Fixed by PR #64 ("fix(web): offer the hook URL only for Webhook-triggered Zaps"). Merged as a32de17.
EOF
)

printf 'Repo: %s\nMode: %s\n\n' "$REPO" "$([[ $APPLY -eq 1 ]] && echo APPLY || echo 'DRY RUN')"
printf '%-6s %-14s %s\n' ISSUE VERDICT EVIDENCE
printf '%-6s %-14s %s\n' ------ -------------- --------

wrote=0
while IFS=$'\t' read -r issue verdict evidence; do
  [[ -z "${issue:-}" ]] && continue
  printf '%-6s %-14s %s\n' "#$issue" "$verdict" "${evidence:0:90}…"

  [[ $APPLY -eq 1 ]] || continue

  state=$(gh issue view "$issue" --json state --jq .state 2>/dev/null)
  if [[ "$state" != "OPEN" ]]; then
    printf '       skipped (state: %s)\n' "${state:-unknown}"
    continue
  fi

  body="$DISCLAIMER

Verified against \`main\`. $evidence

Closing as fixed. Reopen if you can still reproduce it."

  if ! out=$(gh issue comment "$issue" --body "$body" 2>&1); then
    printf '       ✗ %s\n' "$out"
    if [[ "$out" == *"Resource not accessible"* ]]; then
      echo
      echo "Token cannot write to issues. Reconnect GitHub with issues:write, or run"
      echo "this script locally:  gh auth login && ./scripts/triage-backlog.sh --apply"
      exit 1
    fi
    continue
  fi

  if gh issue close "$issue" --reason completed >/dev/null 2>&1; then
    wrote=$((wrote + 1))
    printf '       ✓ commented + closed\n'
  else
    printf '       ✓ commented, close failed\n'
  fi
done <<< "$PLAN"

echo
if [[ $APPLY -eq 1 ]]; then
  echo "Closed $wrote issue(s)."
else
  echo "Dry run. Re-run with --apply to comment and close."
fi
